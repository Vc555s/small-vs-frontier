#!/usr/bin/env python3
"""Write results/t1_robustness.md from the files in results/stress only.

Handles any subset of stages being missing or incomplete: whatever exists is reported,
and a "Not completed" section at the top lists the gaps.

  python make_robustness_report.py [--dir results/stress] [--out results/t1_robustness.md]
"""
import argparse
import json
import math
import os
import statistics as st

from t1_common import load_data
from stress_common import (CLAUDE_CAP, NONE_LABEL, SEEDS, SMALL_TAG, STAGES, claude_calls,
                           read_jsonl, stage_state)

CLAUDE = "Claude via Claude Code CLI (Pro subscription)"


def load(p):
    return read_jsonl(p) if os.path.exists(p) else None


def mcnemar(b, c):
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def f1(golds, preds, labels):
    from sklearn.metrics import f1_score
    return f1_score(golds, [p if p is not None else "__invalid__" for p in preds],
                    labels=labels, average="macro", zero_division=0)


def ms(xs, d=3, pct=False):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "n/a"
    k = 100 if pct else 1
    if len(xs) == 1:
        return f"{k * xs[0]:.{d}f}"
    return f"{k * st.mean(xs):.{d}f} ± {k * st.stdev(xs):.{d}f}"


def mean(xs):
    xs = [x for x in xs if x is not None]
    return st.mean(xs) if xs else None


def auroc(pos, neg):
    from sklearn.metrics import roc_auc_score
    return roc_auc_score([1] * len(pos) + [0] * len(neg), pos + neg)


def seeds_txt(n):
    return f"{n} seed" + ("" if n == 1 else "s")


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="results/stress")
    ap.add_argument("--out", default="results/t1_robustness.md")
    a = ap.parse_args()
    D = a.dir
    _, test, labels = load_data("mteb/banking77")
    labels_none = list(labels) + [NONE_LABEL]
    idx = json.load(open("results/sample500.json"))["indices"]
    bl = json.load(open(os.path.join(D, "build_log.json"))) if os.path.exists(os.path.join(D, "build_log.json")) else None

    # clean references (T1 files, read only)
    clean_claude = {r["idx"]: r for r in read_jsonl("results/preds_claude_code_sample500.jsonl")}
    clean_small = {}
    for s in SEEDS:
        p = f"results/preds_{SMALL_TAG}_n2000_s{s}.jsonl"
        if os.path.exists(p):
            rows = read_jsonl(p)
            clean_small[s] = {i: rows[i] for i in idx}
    cc_correct = {i: clean_claude[i]["pred"] == clean_claude[i]["gold"] for i in idx}
    clean_c_acc = sum(cc_correct.values()) / len(idx)
    clean_c_f1 = f1([clean_claude[i]["gold"] for i in idx], [clean_claude[i]["pred"] for i in idx], labels)
    clean_s_acc = {s: sum(r["pred"] == r["gold"] for r in v.values()) / len(idx) for s, v in clean_small.items()}
    clean_s_f1 = {s: f1([v[i]["gold"] for i in idx], [v[i]["pred"] for i in idx], labels)
                  for s, v in clean_small.items()}

    L = []
    w = L.append
    w("# T1 robustness: fine-tuned Qwen3-4B (2,000 labels) vs " + CLAUDE)
    w("")
    w("Generated by `make_robustness_report.py` from the files in `results/stress/` and the T1 "
      "result files. Every number is read from those files. Small-model numbers are mean ± sample "
      "std over the seeds available (3 planned). Accuracy figures are fractions; drops are in "
      "percentage points.")
    w("")

    # Public version: the pipeline's hidden state files are not published; their content is
    # summarised in run_summary.json. Use it when the state files are absent.
    rs_path = os.path.join(D, "run_summary.json")
    run_summary = json.load(open(rs_path)) if os.path.exists(rs_path) else None
    use_summary = run_summary is not None and not os.path.exists(os.path.join(D, ".done_build"))

    def get_state(s):
        if use_summary:
            row = next((x for x in run_summary["stages"] if x["stage"] == s), None)
            return (row["state"], row["reason"]) if row else ("pending", "")
        return stage_state(D, s)

    def get_gate(setname):
        if use_summary:
            return run_summary["claude_gates"].get(setname)
        gp = os.path.join(D, f".gate_{setname}.json")
        return json.load(open(gp)) if os.path.exists(gp) else None

    def get_meta(s):
        if use_summary:
            row = next((x for x in run_summary["stages"] if x["stage"] == s), None)
            return row["meta"] if row and row["meta"] else None
        mp = os.path.join(D, f".meta_{s}.json")
        return json.load(open(mp)) if os.path.exists(mp) else None

    # ---------------------------------------------------------- gaps
    gaps = []
    for s, kind, _ in STAGES:
        if s == "report":
            continue
        stt, body = get_state(s)
        if stt != "done":
            gaps.append((s, stt, body.splitlines()[0] if body else ""))
    mc = os.path.join(D, ".model_changed")
    if os.path.exists(mc) or gaps:
        w("## Not completed")
        w("")
        if os.path.exists(mc):
            w(f"**The Claude answering model changed during the run; remaining Claude stages were aborted.** "
              f"{open(mc).read().strip()}")
            w("")
        if gaps:
            w("| Stage | State | Reason |")
            w("|---|---|---|")
            for s, stt, why in gaps:
                w(f"| {s} | {stt} | {esc(why)} |")
            w("")
            w("Tables below use whatever finished; rows or sets that are missing are marked n/a.")
            w("")

    # ---------------------------------------------------------- Test A
    w("## Test A: typos and sloppy writing (500 messages)")
    w("")
    cA = load(os.path.join(D, "preds_claude_A.jsonl"))
    sA = {s: load(os.path.join(D, f"preds_small_A_s{s}.jsonl")) for s in SEEDS}
    sA = {s: v for s, v in sA.items() if v}
    rowsA = []
    a_small_drop = a_claude_drop = None
    if sA:
        accs = [sum(r["pred"] == r["gold"] for r in v) / len(v) for v in sA.values()]
        f1s = [f1([r["gold"] for r in v], [r["pred"] for r in v], labels) for v in sA.values()]
        vals = [sum(r["pred"] is not None for r in v) / len(v) for v in sA.values()]
        # clean accuracy on exactly the messages that have a typo prediction (paired)
        cleans = [sum(clean_small[s][r["src_idx"]]["pred"] == clean_small[s][r["src_idx"]]["gold"] for r in v) / len(v)
                  for s, v in sA.items()]
        drops = [c - acc for c, acc in zip(cleans, accs)]
        a_small_drop = mean(drops)
        rowsA.append(f"| {SMALL_TAG} LoRA 2,000 ({seeds_txt(len(sA))}) | {ms(cleans)} | "
                     f"{ms(accs)} | {ms(drops, 1, True)} | {ms([clean_s_f1[s] for s in sA])} | {ms(f1s)} | {ms(vals)} | {len(next(iter(sA.values())))} |")
    if cA:
        n = len(cA)
        acc = sum(r["pred"] == r["gold"] for r in cA) / n
        sub = [r["src_idx"] for r in cA]
        cacc = sum(cc_correct[i] for i in sub) / n
        a_claude_drop = cacc - acc
        rowsA.append(f"| {CLAUDE} | {cacc:.3f} | {acc:.3f} | {100 * (cacc - acc):.1f} | "
                     f"{clean_c_f1:.3f} | {f1([r['gold'] for r in cA], [r['pred'] for r in cA], labels):.3f} | "
                     f"{sum(r['pred'] is not None for r in cA) / n:.3f} | {n} |")
    w("| System | Clean acc | Typo acc | Drop (pts) | Clean macro-F1 | Typo macro-F1 | Typo valid-label rate | n |")
    w("|---|---|---|---|---|---|---|---|")
    L.extend(rowsA or ["| (no results) | | | | | | | |"])
    w("")
    if cA and sA:
        w("Paired comparison on the typo set (exact McNemar, two-sided):")
        w("")
        w("| Seed | Both right | Small only | Claude only | Both wrong | p |")
        w("|---|---|---|---|---|---|")
        cmap = {r["src_idx"]: r["pred"] == r["gold"] for r in cA}
        for s, v in sA.items():
            sm = {r["src_idx"]: r["pred"] == r["gold"] for r in v}
            ks = [k for k in sm if k in cmap]
            b = sum(sm[k] and not cmap[k] for k in ks)
            c = sum(cmap[k] and not sm[k] for k in ks)
            w(f"| {s} | {sum(sm[k] and cmap[k] for k in ks)} | {b} | {c} | "
              f"{sum(not sm[k] and not cmap[k] for k in ks)} | {mcnemar(b, c):.3g} |")
        w("")

    # ---------------------------------------------------------- Test B
    w("## Test B: two problems in one message")
    w("")
    w("This measures graceful behaviour on multi-issue input, **not** correct handling of both "
      "issues: neither system was asked for two labels. A prediction counts as correct if it "
      "equals either of the two gold labels.")
    w("")
    cB = load(os.path.join(D, "preds_claude_B.jsonl"))
    sB = {s: load(os.path.join(D, f"preds_small_B_s{s}.jsonl")) for s in SEEDS}
    sB = {s: v for s, v in sB.items() if v}

    def bstats(v):
        n = len(v)
        first = sum(r["pred"] == r["gold_a"] for r in v) / n
        second = sum(r["pred"] == r["gold_b"] for r in v) / n
        either = sum(r["pred"] in (r["gold_a"], r["gold_b"]) for r in v) / n
        neither = sum(r["pred"] is not None and r["pred"] not in (r["gold_a"], r["gold_b"]) for r in v) / n
        invalid = sum(r["pred"] is None for r in v) / n
        return either, first, second, neither, invalid

    b_small_drop = b_claude_drop = None
    w("| System | Clean acc (reference) | Either-match acc | Drop vs clean (pts) | Picked first | Picked second | Valid but neither | Invalid | n |")
    w("|---|---|---|---|---|---|---|---|---|")
    if sB:
        stats = [bstats(v) for v in sB.values()]
        drops = [clean_s_acc[s] - x[0] for s, x in zip(sB, stats)]
        b_small_drop = mean(drops)
        w(f"| {SMALL_TAG} LoRA 2,000 ({seeds_txt(len(sB))}) | {ms([clean_s_acc[s] for s in sB])} | "
          + " | ".join([ms([x[0] for x in stats]), ms(drops, 1, True)]
                       + [ms([x[k] for x in stats]) for k in (1, 2, 3, 4)]) + f" | {len(next(iter(sB.values())))} |")
    if cB:
        x = bstats(cB)
        b_claude_drop = clean_c_acc - x[0]
        w(f"| {CLAUDE} | {clean_c_acc:.3f} | {x[0]:.3f} | {100 * b_claude_drop:.1f} | {x[1]:.3f} | {x[2]:.3f} | "
          f"{x[3]:.3f} | {x[4]:.3f} | {len(cB)} |")
    if not (sB or cB):
        w("| (no results) | | | | | | | | |")
    w("")
    w("The clean reference is accuracy on the 500 single-issue messages the pairs are built from.")
    w("")
    if cB and sB:
        w("Paired comparison on either-match correctness (exact McNemar):")
        w("")
        w("| Seed | Both right | Small only | Claude only | Both wrong | p |")
        w("|---|---|---|---|---|---|")
        cmap = {r["id"]: r["pred"] in (r["gold_a"], r["gold_b"]) for r in cB}
        for s, v in sB.items():
            sm = {r["id"]: r["pred"] in (r["gold_a"], r["gold_b"]) for r in v}
            ks = [k for k in sm if k in cmap]
            b = sum(sm[k] and not cmap[k] for k in ks)
            c = sum(cmap[k] and not sm[k] for k in ks)
            w(f"| {s} | {sum(sm[k] and cmap[k] for k in ks)} | {b} | {c} | "
              f"{sum(not sm[k] and not cmap[k] for k in ks)} | {mcnemar(b, c):.3g} |")
        w("")

    # ---------------------------------------------------------- Test C
    w("## Test C: messages that fit no category")
    w("")
    c_unavail = os.path.join(D, "test_c_unavailable")
    cres = {}
    if os.path.exists(c_unavail):
        w(f"**Skipped:** {open(c_unavail).read().strip()}")
        w("")
    else:
        def cstats(v):
            ins = [r for r in v if r["gold"] != NONE_LABEL]
            oos = [r for r in v if r["gold"] == NONE_LABEL]
            ia = sum(r["pred"] == r["gold"] for r in ins) / len(ins) if ins else None
            fr = sum(r["pred"] == NONE_LABEL for r in ins) / len(ins) if ins else None
            orc = sum(r["pred"] == NONE_LABEL for r in oos) / len(oos) if oos else None
            ov = sum(r["pred"] == r["gold"] for r in v) / len(v)
            return ia, fr, orc, ov, len(ins), len(oos)

        variants = [("C1", CLAUDE, "extended prompt", [load(os.path.join(D, "preds_claude_C1.jsonl"))]),
                    ("S1", SMALL_TAG + " (T1 adapters)", "extended prompt, no retraining",
                     [load(os.path.join(D, f"preds_small_S1_s{s}.jsonl")) for s in SEEDS]),
                    ("S2", SMALL_TAG + " (T1 adapters)", "original prompt, abstain if confidence < threshold",
                     [load(os.path.join(D, f"preds_small_S2_s{s}.jsonl")) for s in SEEDS]),
                    ("S3", SMALL_TAG + " (retrained)", "2,000 + 200 oos labelled none_of_these, extended prompt",
                     [load(os.path.join(D, f"preds_small_S3_s{s}.jsonl")) for s in SEEDS])]
        w("| Variant | System | Setup | Runs | In-scope acc | False-reject rate | Out-of-scope recall | Overall acc | n in / out |")
        w("|---|---|---|---|---|---|---|---|---|")
        for vid, sysname, setup, runs in variants:
            runs_ok = [r for r in runs if r]
            if not runs_ok:
                w(f"| {vid} | {sysname} | {setup} | 0 | n/a | n/a | n/a | n/a | |")
                continue
            stt = [cstats(r) for r in runs_ok]
            cres[vid] = stt
            w(f"| {vid} | {sysname} | {setup} | {len(runs_ok)} | {ms([x[0] for x in stt])} | {ms([x[1] for x in stt])} | "
              f"{ms([x[2] for x in stt])} | {ms([x[3] for x in stt])} | {stt[0][4]} / {stt[0][5]} |")
        w("")
        w(f"Clean in-scope reference (T1, same 500 messages, no none_of_these option): small model "
          f"{ms(list(clean_s_acc.values()))}, Claude {clean_c_acc:.3f}.")
        w("")
        th = json.load(open(os.path.join(D, "s2_thresholds.json"))) if os.path.exists(os.path.join(D, "s2_thresholds.json")) else {}
        if th:
            w("S2 details. Confidence = probability of the greedy answer (product of its token "
              "probabilities up to and including the end-of-turn token). The threshold was chosen to "
              "maximise overall accuracy on the validation set only (ties: lowest threshold), then "
              "applied once to the test set. AUROC separates in-scope (positive) from out-of-scope "
              "test items by confidence and needs no threshold.")
            w("")
            w("| Seed | Threshold | Validation acc (n) | Test AUROC |")
            w("|---|---|---|---|")
            for s in SEEDS:
                if str(s) not in th:
                    continue
                raw = load(os.path.join(D, f"preds_small_S2raw_s{s}.jsonl"))
                au = "n/a"
                if raw:
                    pos = [r["conf"] for r in raw if r["gold"] != NONE_LABEL]
                    neg = [r["conf"] for r in raw if r["gold"] == NONE_LABEL]
                    if pos and neg:
                        au = f"{auroc(pos, neg):.3f}"
                t = th[str(s)]
                w(f"| {s} | {t['threshold']:.4g} | {t['val_accuracy']:.3f} ({t['val_n']}) | {au} |")
            w("")
        c1 = load(os.path.join(D, "preds_claude_C1.jsonl"))
        if c1:
            cmap = {r["id"]: r["pred"] == r["gold"] for r in c1}
            w("Paired comparison with C1 on overall correctness (exact McNemar):")
            w("")
            w("| Variant | Seed | Both right | Small only | Claude only | Both wrong | p |")
            w("|---|---|---|---|---|---|---|")
            for vid, _, _, runs in variants[1:]:
                for s, v in zip(SEEDS, runs):
                    if not v:
                        continue
                    sm = {r["id"]: r["pred"] == r["gold"] for r in v}
                    ks = [k for k in sm if k in cmap]
                    b = sum(sm[k] and not cmap[k] for k in ks)
                    c = sum(cmap[k] and not sm[k] for k in ks)
                    w(f"| {vid} | {s} | {sum(sm[k] and cmap[k] for k in ks)} | {b} | {c} | "
                      f"{sum(not sm[k] and not cmap[k] for k in ks)} | {mcnemar(b, c):.3g} |")
            w("")
        w("Caveat: CLINC out-of-scope questions are mostly unrelated to banking, so they are easy to "
          "tell apart. Near-miss out-of-scope messages (banking topics outside the 77 intents) would be "
          "harder, and this test does not cover them.")
        w("")

    # ---------------------------------------------------------- production
    w("## What this means for production")
    w("")

    def cmp(name, ds, dc):
        if ds is None or dc is None:
            return f"- **{name}:** not enough results to compare."
        more = "the small model" if ds > dc else "Claude" if dc > ds else "neither"
        return (f"- **{name}:** the small model dropped {100 * ds:.1f} points from its clean score, "
                f"Claude dropped {100 * dc:.1f}. {more[0].upper() + more[1:]} degraded more"
                + (f", by {100 * abs(ds - dc):.1f} points." if more != "neither" else "."))
    w(cmp("Typos (Test A)", a_small_drop, a_claude_drop))
    w(cmp("Two issues in one message (Test B, either-match)", b_small_drop, b_claude_drop))
    if "C1" in cres:
        c1s = cres["C1"][0]
        parts = [f"Claude (C1) kept {c1s[0]:.3f} in-scope accuracy with {c1s[2]:.3f} out-of-scope recall"]
        for vid in ("S1", "S2", "S3"):
            if vid in cres:
                x = cres[vid]
                parts.append(f"{vid} {mean([y[0] for y in x]):.3f} in-scope / {mean([y[2] for y in x]):.3f} recall")
        w("- **Out-of-scope messages (Test C):** " + "; ".join(parts) + ".")
    w("")
    w("Differences inside the seed spread or with McNemar p ≥ 0.05 should be read as ties.")
    w("")

    # ---------------------------------------------------------- methods
    w("## Test construction (frozen before any model output)")
    w("")
    w("- **Base set:** the 500 test indices in `results/sample500.json` (`random.Random(123)`).")
    w("- **Test A:** per message `random.Random(1000 + idx)`; lowercase; remove all punctuation except "
      "apostrophes; each word of 4+ letters (no digits) gets, with probability 0.15, one edit chosen "
      "uniformly from: swap two adjacent inner letters, delete an inner letter, duplicate an inner "
      "letter, replace an inner letter with a QWERTY neighbour. Probability fixed at 0.15 before any model output; no adjustment.")
    w("- **Test B:** base indices shuffled with `random.Random(789)`, paired off, equal-label pairs "
      "re-paired; text `\"<A> Also, <b lowercased first letter>\"`.")
    w("- **Test C:** CLINC150 `oos` items only (never in-scope CLINC intents), fixed banking-keyword "
      "filter, 500 base + out-of-scope test items shuffled with `random.Random(987)`.")
    w("- **Prompts:** original `system_prompt(labels)` from `exp1_routing.py` for A, B and S2; the "
      "extended prompt (one extra label line `none_of_these` plus \"If a message does not fit any "
      "label, answer none_of_these.\") for C1, S1 and S3. Claude gets the same text plus the batch "
      "JSON paragraph.")
    w("")
    if bl:
        w("Counts: " + ", ".join(f"{k} {v}" for k, v in bl["counts"].items()) + ".")
        w("")
        w("### 15 typo examples (Random(15) sample, for review)")
        w("")
        w("| Source idx | Before | After |")
        w("|---|---|---|")
        for e in bl.get("typo_examples", []):
            w(f"| {e['src_idx']} | {esc(e['before'])} | {esc(e['after'])} |")
        w("")
        mb = load(os.path.join(D, "merged250.jsonl"))
        if mb:
            w("### Merged-message examples (first 3)")
            w("")
            for r in mb[:3]:
                w(f"- `{esc(r['text'])}` → gold {r['gold_a']} / {r['gold_b']}")
            w("")
        om = load(os.path.join(D, "oos_mixed.jsonl"))
        if om:
            w("### Out-of-scope examples (first 5 in file order)")
            w("")
            for r in [x for x in om if x["gold"] == NONE_LABEL][:5]:
                w(f"- `{esc(r['text'])}`")
            w("")
        rem = bl.get("removed_out_of_scope", [])
        w(f"### Out-of-scope items removed by the keyword filter ({len(rem)})")
        w("")
        if rem:
            w("| Group | Split | CLINC idx | Matched keyword | Text |")
            w("|---|---|---|---|---|")
            for r in rem:
                w(f"| {r['group']} | {r['split']} | {r['clinc_idx']} | {r['keyword']} | {esc(r['text'])} |")
            w("")
        w("### Decisions recorded by the build stage")
        w("")
        for x in bl.get("decisions", []):
            w(f"- {x}")
        w("")
    if os.path.exists("STRESS_DECISIONS.md"):
        w("## Decisions and deviations (recorded during setup)")
        w("")
        w(open("STRESS_DECISIONS.md").read().split("\n", 1)[1].strip())  # drop its title line
        w("")

    # ---------------------------------------------------------- run facts
    w("## Run facts")
    w("")
    used = run_summary["claude_calls_used"] if use_summary else claude_calls(D)
    w(f"- Claude calls used: {used} of {CLAUDE_CAP} (includes the gate call from a test run of the pipeline).")
    for setname in ("A", "B", "C1"):
        gate = get_gate(setname)
        pp = load(os.path.join(D, f"preds_claude_{setname}.jsonl"))
        line = f"- Claude set {setname}: "
        line += (f"gate {gate}" if gate else "gate not run")
        if pp:
            line += (f"; {len(pp)} predictions, {sum(1 for r in pp if r['error'])} with errors, "
                     f"{len({r['batch'] for r in pp if r['attempt'] > 1})} batches needed retries, "
                     f"models {sorted({r['model'] for r in pp if r['model']})}")
        w(line)
    for s, kind, _ in STAGES:
        meta = get_meta(s)
        if meta:
            w(f"- {s}: {meta}")
    w("")
    w("## Standing caveats about the Claude baseline")
    w("")
    for c in ["Claude saw 25 messages per call; the small model saw one at a time.",
              "The Claude Code CLI adds some prompt text of its own and makes a side call to a small model.",
              "Claude's temperature cannot be set; the small model used greedy decoding.",
              "One Claude run per set; no run-to-run variation is captured.",
              "This is one Claude model through one CLI on a Pro subscription. It is not an API baseline "
              "and says nothing about other frontier models."]:
        w(f"- {c}")
    w("")
